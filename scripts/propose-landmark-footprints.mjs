import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const landmarkRoot = path.join(root, 'assets/pilots/map-rebuild-spike/landmarks');
const terrainRoot = path.dirname(landmarkRoot);
const registryPath = path.join(terrainRoot, 'landmark-collision-contract.json');
const reportPath = path.join(root, 'artifacts/lane-landmark-collision/report.md');
const write = process.argv.includes('--write');
const WALKABLE_HINTS = [
  'approach',
  'arch',
  'blanket',
  'canal-segment',
  'crossing',
  'dressing',
  'far_bank',
  'floodplain',
  'ford',
  'frame',
  'gallery',
  'gate',
  'night_work_road',
  'rail-kit',
  'roadway',
  'shoulders',
  'siege_line',
  'terraces',
];

const round = (value) => Math.round(value * 1000) / 1000;

function proposal(id, bounds) {
  const width = bounds.max[0] - bounds.min[0];
  const depth = bounds.max[1] - bounds.min[1];
  if (WALKABLE_HINTS.some((hint) => id.includes(hint)) || Math.max(width, depth) > 12) return undefined;
  if (Math.min(width, depth) < 0.3 || width * depth < 0.5) return undefined;
  if (Math.max(width, depth) / Math.min(width, depth) <= 1.2) {
    return { kind: 'radius', radius: round(Math.min(width, depth) * 0.36) };
  }
  return { kind: 'rect', w: round(width * 0.72), d: round(depth * 0.72) };
}

function label(footprint) {
  if (!footprint) return 'walkable';
  return footprint.kind === 'radius'
    ? `radius ${footprint.radius}`
    : `rect ${footprint.w} x ${footprint.d}`;
}

const entries = await readdir(landmarkRoot, { withFileTypes: true });
const rows = [];
let authored = 0;
let walkable = 0;
const packs = new Map();

for (const entry of entries.filter((candidate) => candidate.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
  const contractPath = path.join(landmarkRoot, entry.name, `${entry.name}-landmark-pack-contract.json`);
  let contract;
  let text;
  try {
    text = await readFile(contractPath, 'utf8');
    contract = JSON.parse(text);
  } catch {
    continue;
  }
  let changed = false;
  for (const [id, asset] of Object.entries(contract.assets ?? {})) {
    const suggested = proposal(id, asset.bounds);
    if (write && asset.footprint && !suggested) {
      const marker = `      "sha256": "${asset.sha256}",\n      "footprint": ${JSON.stringify(asset.footprint)}`;
      text = text.replace(marker, `      "sha256": "${asset.sha256}"`);
      delete asset.footprint;
      changed = true;
    }
    if (write && !asset.footprint && suggested) {
      asset.footprint = suggested;
      const marker = `      "sha256": "${asset.sha256}"`;
      text = text.replace(marker, `${marker},\n      "footprint": ${JSON.stringify(suggested)}`);
      changed = true;
    }
    const footprint = asset.footprint ?? suggested;
    if (footprint) authored += 1;
    else walkable += 1;
    rows.push(`| ${contract.map} | ${id} | ${label(footprint)} | ${asset.footprint ? 'authored' : suggested ? 'proposal' : 'no proposal'} |`);
  }
  if (changed) await writeFile(contractPath, text);
  packs.set(contract.map, contract);
}

if (write) {
  const maps = {};
  for (const file of (await readdir(terrainRoot)).filter((name) => name.endsWith('-terrain-contract.json')).sort()) {
    const map = file.replace('-terrain-contract.json', '');
    const pack = packs.get(map);
    if (!pack) continue;
    const terrain = JSON.parse(await readFile(path.join(terrainRoot, file), 'utf8'));
    maps[map] = (terrain.landmarkMounts ?? []).flatMap((mount) => {
      const footprint = mount.asset && pack.assets[mount.id]?.footprint;
      return footprint ? [{ id: mount.id, position: [mount.position[0], mount.position[2]], rotation: mount.rotation[1], scale: [mount.scale[0], mount.scale[2]], footprint }] : [];
    });
  }
  await writeFile(registryPath, `${JSON.stringify({ version: 1, maps }, null, 2)}\n`);
}

const report = `# Landmark footprint table

Generated by \`node scripts/propose-landmark-footprints.mjs${write ? ' --write' : ''}\` from planar body bounds. Rectangles and radii are 72% of the visual body. Traversable/compound ids, bodies wider than 12 units, and sub-0.3-unit slivers stay walkable for backwards safety. The repository now contains ${entries.filter((entry) => entry.isDirectory()).length} pack directories (the task's original count was 29).

| Map | Asset | Footprint (sim units) | State |
|---|---|---:|---|
${rows.join('\n')}

Totals: ${authored} blocked assets; ${walkable} walkable assets without a footprint.
`;

await writeFile(reportPath, report);
console.log(`${write ? 'Authored' : 'Proposed'} ${authored} footprints; ${walkable} assets remain walkable.`);

import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const dir='artifacts/s3364';
const run=(c,a)=>execFileSync(c,a,{encoding:'utf8'}).trim();
const result=JSON.parse(fs.readFileSync(`${dir}/ledger-result.json`,'utf8'));
const manifest=JSON.parse(fs.readFileSync(`${dir}/ledger-manifest.json`,'utf8'));
if(result.code!==0||!result.unchanged||!result.headUnchanged)throw Error('Ledger acceptance failed');
if(run('git',['rev-parse','HEAD'])!==manifest.head)throw Error('HEAD moved after tests');
for(const [p,expected] of Object.entries(manifest.hashes))if(createHash('sha256').update(fs.readFileSync(p)).digest('hex')!==expected)throw Error('Tested input moved: '+p);
if(run('git',['diff','--cached','--name-only']))throw Error('Unexpected staged work');
const status=fs.readFileSync('STATUS.md','utf8');
if(status.split('\n')[0]!==fs.readFileSync(`${dir}/tested-line1.txt`,'utf8').trim())throw Error('Lock owner changed');
const body=fs.readFileSync(`${dir}/handoff-body.txt`,'utf8').trim();
const desk=fs.readFileSync(`${dir}/desk-tail.txt`,'utf8').trim();
if(!body.endsWith(desk))throw Error('Owner desk changed');
const previous=fs.readFileSync(`${dir}/predecessor.txt`,'utf8').trim();
if(!status.includes('- **s3363 handoff (line-1 archive):** '+previous))throw Error('Predecessor archive absent');
const stamp=run('date',['-u','+%Y-%m-%dT%H:%MZ']);
const clear=`Last updated: ${stamp} s3364 handoff, lock CLEARED — ${body}`;
fs.writeFileSync('STATUS.md',clear+status.slice(status.indexOf('\n')));
const validation={at:new Date().toISOString(),ledgerCode:result.code,testedInputsUnchanged:true,testedHeadUnchanged:true,deskVerbatim:true,predecessorArchived:true,onlyPostTestInputChange:'STATUS line-1 lock/stamp envelope'};
fs.writeFileSync(`${dir}/closure-validation.json`,JSON.stringify(validation,null,2));
const excludes=new Set(['latest-run-tail.txt','bookkeeping-diff.txt']);
const evidence=fs.readdirSync(dir).filter(n=>!excludes.has(n)).map(n=>`${dir}/${n}`);
run('git',['add','--','STATUS.md','docs/HANDOVER-2026-09-06-attended.md',...evidence]);
run('git',['diff','--cached','--check']);
console.log(run('git',['commit','-m','s3364: handoff lock CLEARED — dry board and healthy heartbeat; ledger green']));
console.log('HANDOFF',run('git',['rev-parse','HEAD']));

import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'chromium' });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto('http://127.0.0.1:5241/?debug&contract=e3-moth-season&nowaves&nospawn&nolevel&seed=e3-moth-season');
await page.waitForFunction(() => window.__GR_TEST__ && (window.__THREE_GAME_DIAGNOSTICS__?.frame ?? 0) > 10, null, { timeout: 60000 });
console.log('booted');
const briefing = page.getByTestId('contract-briefing');
if (await briefing.isVisible()) await page.getByTestId('contract-briefing-dismiss').click();
console.log('dismissed');
const t0 = Date.now();
await page.evaluate(() => window.__GR_TEST__.setDayNightTime(0));
console.log('setDayNightTime ok in', Date.now() - t0, 'ms');
const t1 = Date.now();
const d = await page.evaluate(() => window.__THREE_GAME_DIAGNOSTICS__?.lighting?.dayNight);
console.log('read lighting in', Date.now() - t1, 'ms', JSON.stringify(d));
const p = await page.evaluate(() => ({ frame: window.__THREE_GAME_DIAGNOSTICS__?.frame, power: window.__THREE_GAME_DIAGNOSTICS__?.power?.render, canyon: window.__THREE_GAME_DIAGNOSTICS__?.canyonWorks }));
console.log('probe', JSON.stringify(p));
console.log('errors', JSON.stringify(errors.slice(0, 8)));
await browser.close();

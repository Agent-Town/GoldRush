import fs from 'node:fs';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
const dir = 'artifacts/s3403';
const registryPath = 'assets/rotations/rotation-seeds.json';
const beforeText = fs.readFileSync(registryPath, 'utf8');
const before = JSON.parse(beforeText);
assert(!before.rotations.some(r => r.id === 'r2026w45'));
const now = new Date();
assert(now >= new Date('2026-10-28T00:00:00Z'));
const saltPath = `${process.env.HOME}/.goldrush/rotation-salt`;
const previous = before.rotations.find(r => r.id === 'r2026w44');
const control = JSON.parse(execFileSync(process.execPath, ['scripts/rotation-mint.mjs', '--week', '2026-W44', '--salt-file', saltPath], {encoding: 'utf8'}));
assert.deepEqual(control.rotations[0], previous);
fs.writeFileSync(`${dir}/rotation-before.json`, beforeText);
fs.writeFileSync(`${dir}/rotation-control.json`, JSON.stringify({at: now.toISOString(), previousId: previous.id, exactMatch: true, seedCount: Object.keys(previous.seeds).length, saltPrintedOrCopied: false}, null, 2));
const mint = execFileSync(process.execPath, ['scripts/rotation-mint.mjs', '--week', '2026-W45', '--salt-file', saltPath, '--append', registryPath], {encoding: 'utf8'});
fs.writeFileSync(`${dir}/rotation-mint.txt`, mint);
const afterText = fs.readFileSync(registryPath, 'utf8');
const after = JSON.parse(afterText);
assert.equal(after.rotations.length, before.rotations.length + 1);
assert.deepEqual(after.rotations.slice(0, -1), before.rotations);
const added = after.rotations.at(-1);
assert.equal(added.id, 'r2026w45');
assert.equal(added.opensAt, '2026-11-02T00:00:00.000Z');
assert.equal(added.closesAt, '2026-11-09T00:00:00.000Z');
assert.equal(Object.keys(added.seeds).length, 6);
const skillPath = 'public/skill.md';
const skill = fs.readFileSync(skillPath, 'utf8');
const fence = /(?<=<!-- skillmd-guard:rotations:start -->\n)```json\n[\s\S]*?```(?=\n<!-- skillmd-guard:rotations:end -->)/g;
assert.equal([...skill.matchAll(fence)].length, 1);
fs.writeFileSync(skillPath, skill.replace(fence, '```json\n' + afterText + '```'));
const receipt = {at: new Date().toISOString(), oldRotationsUnchanged: before.rotations.length, addedId: added.id, opensAt: added.opensAt, closesAt: added.closesAt, addedSeeds: Object.keys(added.seeds).length, registryRotations: after.rotations.length, fenceMatchesWholeRegistry: true};
fs.writeFileSync(`${dir}/rotation-invariants.json`, JSON.stringify(receipt, null, 2));
console.log(mint.trim());
console.log(receipt);
